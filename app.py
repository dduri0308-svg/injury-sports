# 나이를 입력받아 5단계 연령대를 반환하는 함수
def get_age_group(age):
    if age <= 12:
        return "유소년기 (1~12세)"
    elif age <= 19:
        return "청소년기 (13~19세)"
    elif age <= 39:
        return "청년기 (20~39세)"
    elif age <= 64:
        return "중장년기 (40~64세)"
    else:
        return "노년기 (65~100세)"

